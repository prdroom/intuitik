// T-1 tokens, T-2 contrast, T-3 distinct states (packet DS-1 section 6).
import fs from 'node:fs';
import path from 'node:path';
import { renderToStaticMarkup } from 'react-dom/server';
import { createElement } from 'react';
import { describe, expect, it } from 'vitest';
import { tokenCustomProperties, tokensCss } from '../build/tokens-css.js';
import { StatusTab } from '../index.js';
import { DESIGN_SYSTEM_DIR, gitBlobId, relativeToDesignSystem, walkFiles, report, reportResults } from './helpers.js';

reportResults();

const TOKENS_FILE = path.join(DESIGN_SYSTEM_DIR, 'tokens.json');
const EXPECTED_BLOB = 'cb4b988b206fce622442039500013de28c222e32';
const readTokens = () => JSON.parse(fs.readFileSync(TOKENS_FILE, 'utf8'));

const HEX = /^#[0-9a-fA-F]{6}$/;

function colourLeaves(node, p = [], out = []) {
  if (typeof node === 'string' && HEX.test(node)) {
    out.push({ path: p, value: node });
  } else if (node && typeof node === 'object' && !Array.isArray(node)) {
    for (const [k, v] of Object.entries(node)) {
      if (!k.startsWith('_')) {
        colourLeaves(v, [...p, k], out);
      }
    }
  }
  return out;
}

// Leaves whose custom property is missing from the CSS text.
function missingColourProperties(tokens, css) {
  return colourLeaves(tokens)
    .filter((leaf) => !css.includes(`--${leaf.path.join('-')}: ${leaf.value};`))
    .map((leaf) => leaf.path.join('.'));
}

// Colour literals (#rgb, #rrggbb, the rgb and rgba functions) in a file's text.
const COLOUR_LITERAL = /#(?:[0-9a-fA-F]{3}){1,2}(?![0-9a-zA-Z_-])|\brgba?\s*\(/g;
function colourLiterals(text) {
  return text.match(COLOUR_LITERAL) ?? [];
}

const SCAN_EXCLUDED = new Set(['tokens.json', 'gallery/fixtures.js']);

describe('T-1 tokens', () => {
  it('T-1 tokens.json is the bytes of prdr blob cb4b988b (git blob computed in the test)', () => {
    const bytes = fs.readFileSync(TOKENS_FILE);
    const blob = gitBlobId(bytes);
    report(`T-1 tokens.json git blob ${blob}`);
    expect(blob).toBe(EXPECTED_BLOB);
    // Negative fixture: one changed byte gives another blob.
    const changed = Buffer.from(bytes);
    changed[changed.length - 2] ^= 1;
    expect(gitBlobId(changed)).not.toBe(EXPECTED_BLOB);
  });

  it('T-1 every leaf colour of tokens.json is a custom property generated by code', () => {
    const tokens = readTokens();
    const css = tokensCss(tokens);
    const leaves = colourLeaves(tokens);
    expect(leaves.length).toBeGreaterThan(30);
    expect(missingColourProperties(tokens, css)).toEqual([]);
    // The properties come from walking the JSON: every generated name is a token path.
    for (const [name] of tokenCustomProperties(tokens)) {
      expect(name).toMatch(/^--(font|color|link|nodeState|size|type)-/);
    }
    // Negative fixture: the CSS without one property fails the check.
    const without = css.replace(`--color-ink: ${tokens.color.ink};`, '');
    expect(missingColourProperties(tokens, without)).toEqual(['color.ink']);
  });

  it('T-1 no colour literal in any .css or .js(x) file of the design system outside tokens.json and the fixtures', () => {
    const files = walkFiles(DESIGN_SYSTEM_DIR).filter((f) => /\.(css|js|jsx)$/.test(f));
    expect(files.length).toBeGreaterThan(10);
    const found = [];
    for (const f of files) {
      const rel = relativeToDesignSystem(f);
      if (SCAN_EXCLUDED.has(rel)) {
        continue;
      }
      for (const lit of colourLiterals(fs.readFileSync(f, 'utf8'))) {
        found.push(`${rel}: ${lit}`);
      }
    }
    report(`T-1 colour literal scan: ${files.length} files, ${found.length} literal(s)`);
    expect(found).toEqual([]);
    // Negative fixture: each literal form is found.
    const sample = ['a { color: #', 'abc; } b { color: #', 'a1b2c3; } c { color: rgb', '(1, 2, 3); }'].join('');
    expect(colourLiterals(sample)).toHaveLength(3);
  });
});

// WCAG 2.x relative luminance and contrast ratio, computed here from the token values.
function luminance(hex) {
  const n = hex.slice(1);
  const lin = (i) => {
    const c = parseInt(n.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * lin(0) + 0.7152 * lin(2) + 0.0722 * lin(4);
}

function contrastRatio(fg, bg) {
  const a = luminance(fg);
  const b = luminance(bg);
  return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
}

// The closed set of 21 text pairs of packet T-2.
function textPairs(t) {
  const pairs = [];
  for (const fg of ['ink', 'sub', 'faint']) {
    for (const bg of ['surface', 'inset', 'canvas']) {
      pairs.push([`${fg}/${bg}`, t.color[fg], t.color[bg]]);
    }
  }
  for (const tone of ['broken', 'attention', 'optional', 'unknown']) {
    pairs.push([`color.${tone} fg/bg`, t.color[tone].fg, t.color[tone].bg]);
    pairs.push([`color.${tone} fg/surface`, t.color[tone].fg, t.color.surface]);
  }
  for (const s of ['failing', 'progressing', 'unknown', 'attention']) {
    pairs.push([`nodeState.${s} fg/bg`, t.nodeState[s].fg, t.nodeState[s].bg]);
  }
  return pairs;
}

describe('T-2 contrast', () => {
  it('T-2 every one of the 21 text pairs is at least 4.5 by the unrounded ratio', () => {
    const tokens = readTokens();
    const pairs = textPairs(tokens);
    expect(pairs).toHaveLength(21);
    expect(new Set(pairs.map((p) => p[0])).size).toBe(21);
    const below = [];
    let lowest = null;
    for (const [name, fg, bg] of pairs) {
      const ratio = contrastRatio(fg, bg);
      report(`T-2 ${name} ${fg} on ${bg} ${ratio.toFixed(6)}`);
      if (ratio < 4.5) {
        below.push(name);
      }
      if (!lowest || ratio < lowest.ratio) {
        lowest = { name, ratio };
      }
    }
    report(`T-2 lowest ${lowest.name} ${lowest.ratio.toFixed(6)}`);
    expect(below).toEqual([]);
    expect(lowest.name).toBe('faint/canvas');
    expect(lowest.ratio).toBeCloseTo(4.524236, 5);
    // Every pair name of _contrast_check is in the set.
    const names = new Set(pairs.map((p) => p[0]));
    const missing = tokens._contrast_check.map((c) => c.pair).filter((n) => !names.has(n));
    expect(missing).toEqual([]);
    // Negative fixture: the canvas colour 9C9CA3 on white is below 4.5.
    expect(contrastRatio('#' + '9C9CA3', '#' + 'FFFFFF')).toBeLessThan(4.5);
  });
});

const allDistinct = (pairs) => new Set(pairs.map((p) => JSON.stringify(p))).size === pairs.length;

describe('T-3 distinct states', () => {
  it('T-3 link (glyph, dash) pairs and node-state (glyph, borderStyle) pairs are all different; Healthy renders no tab', () => {
    const tokens = readTokens();
    const linkPairs = ['connected', 'broken', 'waiting', 'warning', 'unknown', 'optional'].map((s) => [tokens.link[s].glyph, tokens.link[s].dash]);
    const nodePairs = ['failing', 'progressing', 'unknown'].map((s) => [tokens.nodeState[s].glyph, tokens.nodeState[s].borderStyle]);
    report(`T-3 link pairs ${JSON.stringify(linkPairs)}`);
    report(`T-3 node pairs ${JSON.stringify(nodePairs)}`);
    expect(linkPairs).toHaveLength(6);
    expect(allDistinct(linkPairs)).toBe(true);
    expect(allDistinct(nodePairs)).toBe(true);
    expect(renderToStaticMarkup(createElement(StatusTab, { state: 'healthy', text: 'Running' }))).toBe('');
    // Negative fixture: two equal pairs fail.
    expect(allDistinct([...nodePairs, nodePairs[0]])).toBe(false);
  });
});
